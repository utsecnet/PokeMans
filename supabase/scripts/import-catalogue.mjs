/**
 * Copies the shared catalogue out of server/data/catalog.sqlite and into Supabase.
 *
 * Only shared reference data — every Pokémon and every card that exists. Nothing
 * personal: no collections, no want lists, no settings. Those belong to a user, and the
 * user does not exist until someone signs in.
 *
 * Re-runnable. Every table is upserted on its primary key, so running it twice changes
 * nothing and running it after a partial failure simply finishes the job.
 *
 *   node supabase/scripts/import-catalogue.mjs
 *   node supabase/scripts/import-catalogue.mjs --dry-run
 *
 * Needs the service role key, which bypasses row level security — that is the whole
 * reason it can write to tables no user may write to. Put it in supabase/.env (which git
 * ignores) as SUPABASE_SERVICE_ROLE_KEY. It must never reach client/, an environment
 * variable starting with VITE_, or any browser.
 */
import { DatabaseSync } from 'node:sqlite';
import { createClient } from '@supabase/supabase-js';
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const DRY = process.argv.includes('--dry-run');

function readEnv(file) {
  if (!existsSync(file)) return {};
  return Object.fromEntries(
    readFileSync(file, 'utf8')
      .split('\n')
      .filter((l) => l.trim() && !l.trimStart().startsWith('#') && l.includes('='))
      .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
  );
}

const env = { ...readEnv(path.join(repo, 'client/.env.local')), ...readEnv(path.join(repo, 'supabase/.env')) };
const url = env.VITE_SUPABASE_URL ?? env.SUPABASE_URL;
const serviceKey = env.SUPABASE_SERVICE_ROLE_KEY;

if (!url) throw new Error('No Supabase URL. Expected VITE_SUPABASE_URL in client/.env.local.');
if (!serviceKey && !DRY) {
  throw new Error(
    'No SUPABASE_SERVICE_ROLE_KEY.\n\n' +
      '  Supabase dashboard > Project Settings > API Keys > service_role (click Reveal)\n' +
      '  Put it in supabase/.env as:  SUPABASE_SERVICE_ROLE_KEY=...\n\n' +
      'That file is git-ignored. The key bypasses row level security entirely, so it must\n' +
      'never appear in client/, in a VITE_ variable, or anywhere a browser can read it.',
  );
}

const db = new DatabaseSync(path.join(repo, 'server/data/catalog.sqlite'), { readOnly: true });
const sb = DRY ? null : createClient(url, serviceKey, { auth: { persistSession: false } });

/** 1999/01/09 -> 1999-01-09. Postgres reads the slashed form by DateStyle, which is a
 *  setting, and a date that depends on a server setting is a date waiting to be wrong. */
const asDate = (v) => (v ? String(v).replace(/\//g, '-') : null);
const asBool = (v) => v === 1 || v === true || v === '1';

/**
 * Parents before children: Postgres enforces the foreign keys that SQLite only declared,
 * so a card inserted before its set is rejected rather than quietly accepted.
 */
const TABLES = [
  { name: 'types', conflict: 'id', sql: 'SELECT id, name FROM types' },
  { name: 'abilities', conflict: 'id', sql: 'SELECT id, name, effect FROM abilities' },
  {
    name: 'pokemon',
    conflict: 'id',
    sql: `SELECT id, national_dex_number, name, generation, height, weight, base_experience,
                 flavor_text, sprite_url, artwork_url, is_default_variety, variant_label
          FROM pokemon`,
    map: (r) => ({ ...r, is_default_variety: asBool(r.is_default_variety) }),
  },
  { name: 'pokemon_types', conflict: 'pokemon_id,type_id', sql: 'SELECT pokemon_id, type_id, slot FROM pokemon_types' },
  {
    name: 'pokemon_abilities',
    conflict: 'pokemon_id,ability_id',
    sql: 'SELECT pokemon_id, ability_id, is_hidden, slot FROM pokemon_abilities',
    map: (r) => ({ ...r, is_hidden: asBool(r.is_hidden) }),
  },
  {
    name: 'stats',
    conflict: 'pokemon_id',
    sql: 'SELECT pokemon_id, hp, attack, defense, special_attack, special_defense, speed FROM stats',
  },
  {
    name: 'evolutions',
    // id is generated by Postgres, so the natural key is what makes this idempotent.
    conflict: 'pokemon_id,evolves_into_id',
    sql: 'SELECT pokemon_id, evolves_into_id, trigger, min_level, item FROM evolutions',
  },
  { name: 'tcg_series', conflict: 'name', sql: 'SELECT name, logo_url FROM tcg_series' },
  {
    name: 'tcg_sets',
    conflict: 'id',
    sql: 'SELECT id, name, series, release_date, symbol_url, logo_url FROM tcg_sets',
    map: (r) => ({ ...r, release_date: asDate(r.release_date) }),
  },
  {
    name: 'tcg_cards',
    conflict: 'id',
    sql: `SELECT id, name, number, set_id, set_name, series, rarity, supertype, illustrator,
                 release_date, image_small, image_large, image_webp, tcgdex_id
          FROM tcg_cards`,
    map: (r) => ({ ...r, release_date: asDate(r.release_date) }),
  },
  {
    name: 'tcg_card_variants',
    conflict: 'card_id,position',
    sql: 'SELECT card_id, position, type, subtype, stamp, size, foil FROM tcg_card_variants',
  },
  { name: 'tcg_card_pokemon', conflict: 'card_id,pokemon_id', sql: 'SELECT card_id, pokemon_id FROM tcg_card_pokemon' },
  { name: 'tcg_card_types', conflict: 'card_id,type', sql: 'SELECT card_id, type, slot FROM tcg_card_types' },
];

const BATCH = 1000;
const started = Date.now();
let grandTotal = 0;

for (const t of TABLES) {
  const rows = db.prepare(t.sql).all().map(t.map ?? ((r) => r));
  process.stdout.write(`   ${t.name.padEnd(20)} ${String(rows.length).padStart(6)} rows `);

  if (DRY) {
    console.log('(dry run)');
    grandTotal += rows.length;
    continue;
  }

  for (let i = 0; i < rows.length; i += BATCH) {
    const chunk = rows.slice(i, i + BATCH);
    const { error } = await sb.from(t.name).upsert(chunk, { onConflict: t.conflict, defaultToNull: true });
    if (error) {
      console.log('\n');
      console.error(`   ${t.name}: failed at row ${i}`);
      console.error(`   ${error.code ?? ''} ${error.message}`);
      if (error.details) console.error(`   ${error.details}`);
      console.error('\n   Nothing was rolled back — re-run to resume; upserts make that safe.');
      process.exit(1);
    }
    process.stdout.write('.');
  }
  console.log(' ok');
  grandTotal += rows.length;
}

db.close();
console.log(
  `\n   ${grandTotal.toLocaleString()} rows in ${((Date.now() - started) / 1000).toFixed(1)}s` +
    (DRY ? ' (dry run — nothing written)' : ''),
);
